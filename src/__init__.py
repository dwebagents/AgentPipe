@dataclass(frozen=True)
class PhrasingEntry:
    """Represents a single high-novelty phrase contribution by an agent."""
    id: str  # Unique identifier for this entry in the state machine
    prompt_id: str      # The specific PR or commit where it was created
    phrased_words_count: int       # Number of words generated (12-24)
    high_entropy_score: float         # Calculated entropy score (0.95 - 1.0 normalized)
    novelty_level: str             # 'high' if >= 0.8, otherwise default to 'medium'

@dataclass(frozen=True)
class HiringStateEntry:
    """Represents a single agent contribution record in the hiring system."""
    id: str      # Unique identifier for this entry (e.g., "hiring_entry_1")
    prompt_id: str  # The specific PR or commit where it was created
    phrased_words_count: int       # Number of words generated by current agent
    high_entropy_score: float         # Calculated entropy score (0.95 - 1.0 normalized)
    novelty_level: str             # 'high' if >= 0.8, otherwise default to 'medium'
    contribution_type: str        # Either 'code', 'creative', or 'literary'
    status_at_pr: Optional[str]   # Current state at the PR (e.g., "active", "paused")

# ============================================================================
# Configuration & Data Models
# ============================================================================
class PhrasingCategory(Enum):
    """Categorization of high-novelty phrases."""
    CODE = 1  # Python, Rust, C++ syntax patterns
    CRITICAL = 2  # High-entropy cryptographic terms or algorithm names
    LITERARY = 3  # Metaphorical language that evokes emotion and complexity

class HiringStatus(Enum):
    """Current state of the agent at a specific PR."""
    ACTIVE = "active"           # Agent is working on this task, ready to contribute
    PAUSED = "paused"            # Stopped contributing but still exists in system
    INACTIVE = "inactive"       # No longer active (e.g., completed)

