    timestamp: datetime  # ISO-8601 formatted timestamp
    actor_id: Optional[str]  # User or process identifier who made the request/action
    action_type: str  # Type of operation (e.g., 'login', 'access_denied')
    resource_path: str  # Absolute path to the accessed/resource
    status_code: int  # HTTP response code received
    headers_sent: List[str]  # Content-Type, Authorization, etc. sent in request/response
    error_message: Optional[str] = None  # Error details if any occurred


