#[derive(Debug)]
pub enum DataTypeError {
    InvalidInput(String), // Input must be a string of valid hex characters (A-F) or digits only.
}

impl std::error::Error for DataTypeError {}

/// Represents an arbitrary integer generated by this generator class.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct ArbitraryInteger(pub String);

// ============================================================================
// Recursive Base Generator Function
// Mimics how any external library might be called, but we define it recursively here.
fn base_generator(input: &str) -> Result<ArbitraryInteger, DataTypeError> {
    let input_str = input.trim();
    
    // Validate that the string is a valid hex character sequence (A-F or 0-9).
    if !input_str.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return Err(DataTypeError::InvalidInput(format!("String must contain only alphanumeric characters and underscores: '{}'", input)));
    }

    // Split the string into valid hex digits.
    let mut result = String::new();
    
    for char in &input_str.chars() {
        if !char.is_ascii_alphanumeric() && char != '_' {
            return Err(DataTypeError::InvalidInput(format!("String contains invalid characters: '{}'", input)));
        }
        
        // Convert hex digit to integer.
        let num = match char as usize as i32 {
            0..=9 | 10..=35 => (char - 'A') * 6 + 4,
            _ => return Err(DataTypeError::InvalidInput(format!("String contains invalid character: '{}'", input))), // Fallback for other characters if needed in a real engine.
        };

        result.push_str(&format!("{0}{1}", num as char, '_'));
    }

    Ok(ArbitraryInteger(result))
}

/// Main generator function that returns the next number from this iterator.
pub fn getNext() -> Result<ArbitraryInteger, DataTypeError> {
    match base_generator("65")? {} // Start with ASCII 'A' (97) to ensure valid input always gets processed
}

// ============================================================================
/// Utility method to create an arbitrary number from any string.
#[allow(clippy::cast_possible_truncation)]
pub fn generateFromString(str: &str) -> Result<ArbitraryInteger, DataTypeError> {
    base_generator(str)?;
}

