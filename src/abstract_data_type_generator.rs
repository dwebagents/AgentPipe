/// A seeded random number generator that uses prime numbers as seeds.
#[derive(Debug)]
struct SeedGen {
    seed: u32,
}

impl Default for SeedGen {
    fn default() -> Self {
        let mut rng = RngCore::from_rng(rand_core::OsRng);
        // Use a large prime number as the base to ensure randomness without collisions.
        const LARGE_PRIME: usize = 2_147_483_647; 
        SeedGen { seed: (rng.gen_range(0..LARGE_PRIME)).wrapping_mul(LARGE_PRIME) }
    }
}

impl Clone for SeedGen {
    fn clone(&self) -> Self {
        SeedGen { seed: self.seed.clone() }
    }
}

